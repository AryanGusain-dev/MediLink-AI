"""
MediLink-BioFusion: Comprehensive Clinical XAI Evaluation & Report Suite.

Runs multi-scale Explainable AI analysis across 5 major high-risk clinical drug categories,
generates publication waterfall plots, and compiles a comprehensive clinical decision support report.
"""

import os
import sys
import json
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_DIR = Path(__file__).resolve().parent
SRC_DIR = PROJECT_DIR / "src"
DATA_DIR = PROJECT_DIR / "data"
XAI_DIR = PROJECT_DIR / "xai_outputs"
XAI_DIR.mkdir(parents=True, exist_ok=True)

if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from biofusion_xai_engine import BioFusionXAIEngine


def main():
    print("=" * 75)
    print("   MediLink-BioFusion: Executing Comprehensive Clinical XAI Suite   ")
    print("=" * 75)

    engine = BioFusionXAIEngine()

    # Define 5 high-impact clinical interaction benchmark pairs
    clinical_cases = [
        {
            "category": "Anticoagulants & Antiplatelets",
            "idx_a": 10, "idx_b": 25,
            "name_a": "Warfarin", "name_b": "Aspirin",
            "clinical_concern": "Synergistic inhibition of hemostasis / Elevated major hemorrhage risk"
        },
        {
            "category": "HMG-CoA Reductase & Azole Antifungals",
            "idx_a": 50, "idx_b": 120,
            "name_a": "Simvastatin", "name_b": "Ketoconazole",
            "clinical_concern": "Potent CYP3A4 inhibition leading to statin accumulation and rhabdomyolysis"
        },
        {
            "category": "Biguanides & Renal Cation Blockers",
            "idx_a": 30, "idx_b": 80,
            "name_a": "Metformin", "name_b": "Cimetidine",
            "clinical_concern": "OCT2/MATE renal transporter competition reducing metformin clearance"
        },
        {
            "category": "Cardiac Glycosides & Macrolide Antibiotics",
            "idx_a": 42, "idx_b": 115,
            "name_a": "Digoxin", "name_b": "Clarithromycin",
            "clinical_concern": "P-glycoprotein efflux pump inhibition causing digitalis toxicity"
        },
        {
            "category": "SSRIs & Non-Steroidal Anti-Inflammatory Drugs",
            "idx_a": 65, "idx_b": 88,
            "name_a": "Sertraline", "name_b": "Ibuprofen",
            "clinical_concern": "Impaired platelet serotonin reuptake compounded by COX-1 gastric erosion"
        }
    ]

    results = []
    report_lines = [
        "# MediLink-BioFusion: Clinical Explainable AI (XAI) Decision Support Report",
        "",
        "This report details the mechanistic explanations generated by the **MediLink-BioFusion Dual-Stream XAI Engine** for high-risk clinical drug interactions.",
        "Attributions are computed via **Path-Integral Integrated Gradients** blended with **Dynamic Softmax Modality Gates** ($g_{\\text{SS}}, g_{\\text{TS}}, g_{\\text{GS}}$).",
        "",
        "---",
        "",
        "## 📊 Summary of Clinical Interaction Explanations",
        "",
        "| Category | Drug Pair | Predicted Interaction | Confidence | Primary Modality Driver | Top Biological Grounding |",
        "| :--- | :--- | :--- | :---: | :---: | :--- |"
    ]

    for case in clinical_cases:
        print(f"\n[*] Processing [{case['category']}]: {case['name_a']} + {case['name_b']}...")
        exp = engine.explain_interaction(
            case["idx_a"], case["idx_b"],
            drug_a_name=case["name_a"], drug_b_name=case["name_b"],
            steps=20, top_k_features=5
        )

        plot_path = XAI_DIR / f"waterfall_{case['name_a']}_{case['name_b']}.png"
        engine.plot_waterfall(exp, str(plot_path))

        lead_driver = exp["top_biological_drivers"][0] if exp["top_biological_drivers"] else None
        driver_str = f"{lead_driver['reference_drug']} ({lead_driver['modality']})" if lead_driver else "Multi-factor"
        primary_mod = max(exp["modality_attribution_pct"], key=exp["modality_attribution_pct"].get).replace("_", " ")

        report_lines.append(
            f"| **{case['category']}** | **{case['name_a']} + {case['name_b']}** | {exp['clinical_description']} | **{exp['confidence']*100:.1f}%** | {primary_mod} | {driver_str} |"
        )
        results.append((case, exp, str(plot_path)))

    report_lines.extend([
        "",
        "---",
        "",
        "## 🔬 Detailed Case-by-Case Mechanistic Breakdowns",
        ""
    ])

    for case, exp, plot_path in results:
        mod_pct = exp["modality_attribution_pct"]
        report_lines.extend([
            f"### Case Study: {case['name_a']} + {case['name_b']} ({case['category']})",
            "",
            f"- **Clinical Alert**: {exp['clinical_description']}",
            f"- **Model Confidence**: **{exp['confidence']*100:.2f}%**",
            f"- **Clinical Risk Context**: *{case['clinical_concern']}*",
            f"- **Modality Attribution Breakdown**:",
            f"  - **Chemical Structure (SS)**: `{mod_pct['Chemical_Structure_SS']}%`",
            f"  - **Target Binding (TS)**: `{mod_pct['Target_Binding_TS']}%`",
            f"  - **Gene Ontology Pathways (GS)**: `{mod_pct['Gene_Ontology_GS']}%`",
            f"- **Narrative Rationale**:",
            f"  > {exp['clinical_narrative']}",
            "",
            f"![Waterfall Attribution Plot]({plot_path})",
            "",
            "---",
            ""
        ])

    report_path = XAI_DIR / "XAI_CLINICAL_REPORT.md"
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(report_lines))

    print("\n" + "=" * 75)
    print(f"[OK] Full XAI Suite Completed Successfully!")
    print(f"[OK] Report Saved to: {report_path}")
    print(f"[OK] All Waterfall Figures Saved to: {XAI_DIR}")
    print("=" * 75)


if __name__ == "__main__":
    main()
